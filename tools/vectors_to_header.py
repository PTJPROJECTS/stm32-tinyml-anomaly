#!/usr/bin/env python3
"""Take a few vectors from host/vectors/test_vectors.bin and write them as a
C header, so the firmware can run the same check on the board at boot."""
import argparse
import struct

import numpy as np


def read(path):
    with open(path, "rb") as f:
        assert f.read(4) == b"TVEC"
        n, win, nf, no = struct.unpack("<4I", f.read(16))
        rec = np.dtype([("win", "<u2", win), ("feat", "<f4", nf), ("inp", "i1", nf),
                        ("out", "i1", no), ("label", "u1")])
        return np.frombuffer(f.read(), rec, count=n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="host/vectors/test_vectors.bin")
    ap.add_argument("--dst", default="firmware/src/selftest_vectors.h")
    ap.add_argument("--per-class", type=int, default=2)
    a = ap.parse_args()
    v = read(a.src)
    pick = np.concatenate([np.flatnonzero(v["label"] == c)[:a.per_class] for c in range(4)])
    v = v[pick]
    with open(a.dst, "w") as f:
        f.write("// Generated by tools/vectors_to_header.py from test_vectors.bin\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define SELFTEST_N {len(v)}\n\n")
        f.write("static const uint16_t selftest_win[SELFTEST_N][512] = {\n")
        for r in v:
            vals = ", ".join(str(x) for x in r["win"])
            f.write(f"  {{{vals}}},\n")
        f.write("};\n\n")
        f.write("// TFLite interpreter output for the same window (int8 scores)\n")
        f.write("static const int8_t selftest_out[SELFTEST_N][4] = {\n")
        for r in v:
            f.write("  {" + ", ".join(str(int(x)) for x in r["out"]) + "},\n")
        f.write("};\n\n")
        f.write("static const uint8_t selftest_label[SELFTEST_N] = {"
                + ", ".join(str(int(r["label"])) for r in v) + "};\n")
    print(f"wrote {len(v)} vectors to {a.dst}")


if __name__ == "__main__":
    main()
