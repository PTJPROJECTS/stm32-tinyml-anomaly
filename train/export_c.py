"""Write the .tflite model and feature normalization into C source files."""
import numpy as np

HEADER = "// Generated by train/train.py. Do not edit by hand.\n"


def _bytes_to_c(data, per_line=12):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def _floats_to_c(v, per_line=4):
    lines = []
    for i in range(0, len(v), per_line):
        lines.append("  " + ", ".join(f"{float(x):.9g}f" for x in v[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_model(tflite_bytes, mean, inv_std, classes, h_path, c_path):
    n = len(mean)
    with open(h_path, "w") as f:
        f.write(HEADER)
        f.write("#ifndef MODEL_DATA_H\n#define MODEL_DATA_H\n\n#include <stdint.h>\n\n")
        f.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        f.write(f"#define MODEL_N_FEATURES {n}\n#define MODEL_N_CLASSES {len(classes)}\n\n")
        f.write("extern const unsigned char g_model_tflite[];\n")
        f.write("extern const unsigned int g_model_tflite_len;\n")
        f.write("extern const float g_feat_mean[MODEL_N_FEATURES];\n")
        f.write("extern const float g_feat_inv_std[MODEL_N_FEATURES];\n")
        f.write("extern const char *const g_class_names[MODEL_N_CLASSES];\n\n")
        f.write("#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
    with open(c_path, "w") as f:
        f.write(HEADER)
        f.write('#include "model_data.h"\n\n')
        f.write("// 16 byte alignment, the flatbuffer needs at least 4 and some\n")
        f.write("// CMSIS-NN kernels like aligned weights.\n")
        f.write(f"alignas(16) const unsigned char g_model_tflite[] = {{\n{_bytes_to_c(tflite_bytes)}\n}};\n")
        f.write(f"const unsigned int g_model_tflite_len = {len(tflite_bytes)};\n\n")
        f.write(f"const float g_feat_mean[MODEL_N_FEATURES] = {{\n{_floats_to_c(mean)}\n}};\n\n")
        f.write(f"const float g_feat_inv_std[MODEL_N_FEATURES] = {{\n{_floats_to_c(inv_std)}\n}};\n\n")
        names = ", ".join(f'"{c}"' for c in classes)
        f.write(f"const char *const g_class_names[MODEL_N_CLASSES] = {{{names}}};\n")


def write_vectors(path, windows_u16, feats_f32, xq_i8, yq_i8, labels):
    """One binary file the host test reads.

    header: 'TVEC', u32 count, u32 win, u32 n_feat, u32 n_out
    per vector: u16 window[win], f32 feat[n_feat], i8 in[n_feat],
                i8 out[n_out], u8 label
    """
    n, win = windows_u16.shape
    nf = feats_f32.shape[1]
    no = yq_i8.shape[1]
    with open(path, "wb") as f:
        f.write(b"TVEC")
        f.write(np.array([n, win, nf, no], "<u4").tobytes())
        for i in range(n):
            f.write(windows_u16[i].astype("<u2").tobytes())
            f.write(feats_f32[i].astype("<f4").tobytes())
            f.write(xq_i8[i].astype(np.int8).tobytes())
            f.write(yq_i8[i].astype(np.int8).tobytes())
            f.write(np.uint8(labels[i]).tobytes())
